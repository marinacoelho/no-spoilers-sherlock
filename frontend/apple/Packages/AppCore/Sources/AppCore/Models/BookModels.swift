import Foundation

/// Represents a mystery novel or literary work in a universe.
public struct Book: Sendable, Equatable, Identifiable, Codable {
    /// Unique identifier for the book (e.g., `"study_in_scarlet"`).
    public let id: String

    /// Identifier for the literary universe (e.g., `"sherlock_holmes"`).
    public let universeId: String

    /// Chronological or publication order within the universe.
    public let bookOrder: Int

    /// Full title of the book.
    public let title: String

    /// Name of the author.
    public let author: String

    /// Total number of chapters in the book.
    public let totalChapters: Int

    /// Creates a new `Book` model instance.
    ///
    /// - Parameters:
    ///   - id: Unique identifier for the book.
    ///   - universeId: Identifier for the literary universe.
    ///   - bookOrder: Order of the book within the universe.
    ///   - title: Full title of the book.
    ///   - author: Name of the author.
    ///   - totalChapters: Total number of chapters in the book.
    public init(
        id: String = "",
        universeId: String = "",
        bookOrder: Int = 1,
        title: String = "",
        author: String = "",
        totalChapters: Int = 1
    ) {
        self.id = id
        self.universeId = universeId
        self.bookOrder = bookOrder
        self.title = title
        self.author = author
        self.totalChapters = totalChapters
    }
}

/// Represents a single chapter within a `Book`.
public struct Chapter: Sendable, Equatable, Identifiable, Codable {
    /// Unique identifier for the chapter (e.g., `"study_in_scarlet_ch01"`).
    public let id: String

    /// Identifier of the parent `Book`.
    public let bookId: String

    /// 1-based sequential chapter number.
    public let chapterOrder: Int

    /// Title of the chapter.
    public let title: String

    /// Creates a new `Chapter` model instance.
    ///
    /// - Parameters:
    ///   - id: Unique identifier for the chapter.
    ///   - bookId: Identifier of the parent book.
    ///   - chapterOrder: 1-based sequential chapter number.
    ///   - title: Title of the chapter.
    public init(
        id: String = "",
        bookId: String = "",
        chapterOrder: Int = 1,
        title: String = ""
    ) {
        self.id = id
        self.bookId = bookId
        self.chapterOrder = chapterOrder
        self.title = title
    }
}

/// Represents a spoiler-bounded narrative text chunk belonging to a specific chapter.
public struct Chunk: Sendable, Equatable, Identifiable, Codable {
    /// Unique identifier for the chunk (e.g., `"chunk_study_in_scarlet_ch01_001"`).
    public let id: String

    /// Identifier of the parent `Book`.
    public let bookId: String

    /// Order of the parent book within the universe.
    public let bookOrder: Int

    /// Identifier of the parent `Chapter`.
    public let chapterId: String

    /// 1-based sequential chapter number used for spoiler boundary filtering.
    public let chapterOrder: Int

    /// 1-based index of the chunk within the chapter.
    public let chunkIndex: Int

    /// Raw narrative summary or excerpt content of the chunk.
    public let content: String

    /// Creates a new `Chunk` model instance.
    ///
    /// - Parameters:
    ///   - id: Unique identifier for the chunk.
    ///   - bookId: Identifier of the parent book.
    ///   - bookOrder: Order of the parent book.
    ///   - chapterId: Identifier of the parent chapter.
    ///   - chapterOrder: 1-based sequential chapter number.
    ///   - chunkIndex: 1-based index within the chapter.
    ///   - content: Narrative summary or excerpt text.
    public init(
        id: String = "",
        bookId: String = "",
        bookOrder: Int = 1,
        chapterId: String = "",
        chapterOrder: Int = 1,
        chunkIndex: Int = 1,
        content: String = ""
    ) {
        self.id = id
        self.bookId = bookId
        self.bookOrder = bookOrder
        self.chapterId = chapterId
        self.chapterOrder = chapterOrder
        self.chunkIndex = chunkIndex
        self.content = content
    }
}

/// Identifies the participant who authored a `ChatMessage`.
public enum MessageSender: String, Sendable, Equatable, Codable {
    /// A message sent by the human reader.
    case user

    /// A spoiler-bounded response or illustration generated by the Sherlock AI assistant.
    case ai

    /// A system status, welcome, book switch, or error notification message.
    case system
}

/// Represents a single message entry in the Sherlock conversation transcript.
public struct ChatMessage: Sendable, Equatable, Identifiable, Codable {
    /// Unique identifier for the message.
    public let id: String

    /// Participant who sent the message.
    public let sender: MessageSender

    /// Markdown-formatted text or caption of the message.
    public let text: String

    /// Timestamp in milliseconds since the Unix epoch.
    public let timestamp: Int64

    /// Target chapter boundary applied to or extracted from this message, if any.
    public let extractedChapter: Int?

    /// Sorted list of chapter numbers cited in generating this response.
    public let citedChapters: [Int]

    /// Indicates whether the message was generated using an on-device or offline model.
    public let isOfflineMode: Bool

    /// Optional PNG/image binary payload for Victorian scene illustrations.
    public let imageData: Data?

    /// Indicates whether this message represents a Victorian scene visualization card.
    public let isSceneVisualization: Bool

    /// Creates a new `ChatMessage` instance.
    ///
    /// - Parameters:
    ///   - id: Unique identifier for the message. Defaults to a new UUID string.
    ///   - sender: Participant who authored the message.
    ///   - text: Text or caption of the message.
    ///   - timestamp: Timestamp in milliseconds since epoch.
    ///   - extractedChapter: Optional chapter boundary associated with the message.
    ///   - citedChapters: List of chapter numbers cited in the answer.
    ///   - isOfflineMode: Flag indicating offline/on-device execution.
    ///   - imageData: Optional raw PNG data for scene illustrations.
    ///   - isSceneVisualization: Flag indicating a scene visualization message.
    public init(
        id: String = UUID().uuidString,
        sender: MessageSender,
        text: String,
        timestamp: Int64 = Int64(Date().timeIntervalSince1970 * 1000),
        extractedChapter: Int? = nil,
        citedChapters: [Int] = [],
        isOfflineMode: Bool = false,
        imageData: Data? = nil,
        isSceneVisualization: Bool = false
    ) {
        self.id = id
        self.sender = sender
        self.text = text
        self.timestamp = timestamp
        self.extractedChapter = extractedChapter
        self.citedChapters = citedChapters
        self.isOfflineMode = isOfflineMode
        self.imageData = imageData
        self.isSceneVisualization = isSceneVisualization
    }
}

/// Encapsulates the output of a spoiler-bounded Victorian scene illustration request.
public struct SceneIllustrationResult: Sendable, Equatable, Codable {
    /// Descriptive caption accompanying the generated illustration.
    public let caption: String

    /// Pre-encoded PNG or bitmap image data representing the Victorian engraving.
    public let imageData: Data?

    /// Creates a new `SceneIllustrationResult`.
    ///
    /// - Parameters:
    ///   - caption: Descriptive caption for the scene illustration.
    ///   - imageData: Encoded PNG image bytes, if available.
    public init(caption: String, imageData: Data?) {
        self.caption = caption
        self.imageData = imageData
    }
}
